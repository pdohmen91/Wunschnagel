import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { openNewList } from './ui'

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
})

test('searching and choosing a new symbol persists when the list is saved and reloaded', async ({ page }) => {
  await page.getByRole('button', { name: 'Liste bearbeiten', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Wunschliste bearbeiten', exact: true })
  const trigger = dialog.getByRole('button', { name: /^Symbol auswählen/ })
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.click()
  const picker = dialog.getByRole('region', { name: 'Symbolauswahl', exact: true })
  await expect(picker.getByRole('group', { name: 'Symbole', exact: true }).getByRole('button')).toHaveCount(128)
  await picker.getByRole('searchbox', { name: 'Symbole suchen', exact: true }).fill('Gitarre')
  await expect(picker.getByRole('status')).toHaveText('1 Symbol')
  await picker.getByRole('button', { name: 'Gitarre 🎸', exact: true }).click()
  await expect(picker).toHaveCount(0)
  await expect(trigger).toHaveAccessibleName('Symbol auswählen, aktuell: Gitarre 🎸')
  await expect(trigger).toBeFocused()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(page.locator('.list-cover')).toHaveText('🎸')
  await page.reload()
  await expect(page.locator('.list-cover')).toHaveText('🎸')
  await page.getByRole('button', { name: 'Liste bearbeiten', exact: true }).click()
  await expect(page.getByRole('button', { name: /^Symbol auswählen/ })).toHaveAccessibleName('Symbol auswählen, aktuell: Gitarre 🎸')
})

test('categories, no results, keyboard selection and Escape keep the list form open', async ({ page }) => {
  await openNewList(page)
  const dialog = page.getByRole('dialog', { name: 'Neue Wunschliste', exact: true })
  await dialog.getByRole('textbox', { name: 'Name deiner Liste', exact: true }).fill('Sport & Freizeit')
  const trigger = dialog.getByRole('button', { name: /^Symbol auswählen/ })
  await trigger.focus(); await trigger.press('Enter')
  const picker = dialog.getByRole('region', { name: 'Symbolauswahl', exact: true })
  await picker.getByRole('combobox', { name: 'Symbolkategorie', exact: true }).selectOption('sports')
  await expect(picker.getByRole('group', { name: 'Symbole', exact: true }).getByRole('button')).toHaveCount(16)
  const search = picker.getByRole('searchbox', { name: 'Symbole suchen', exact: true })
  await search.fill('nichtsgefunden123')
  await expect(picker).toContainText('Kein passendes Symbol gefunden.')
  await picker.getByRole('button', { name: 'Alle Symbole anzeigen', exact: true }).click()
  await expect(picker.getByRole('status')).toHaveText('128 Symbole')
  await search.fill('fussball')
  await expect(picker.getByRole('button', { name: 'Fußball ⚽', exact: true })).toBeVisible()
  await search.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(trigger).toHaveAccessibleName('Symbol auswählen, aktuell: Fußball ⚽')
  await trigger.click()
  const symbols = picker.getByRole('group', { name: 'Symbole', exact: true }).getByRole('button')
  await symbols.first().focus(); await symbols.first().press('ArrowRight')
  await expect(symbols.nth(1)).toBeFocused()
  await symbols.nth(1).press('End')
  await expect(symbols.last()).toBeFocused()
  await symbols.last().press('Escape')
  await expect(picker).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByRole('textbox', { name: 'Name deiner Liste', exact: true }).click()
  await expect(picker).toHaveCount(0)
  await expect(dialog.getByRole('textbox', { name: 'Name deiner Liste', exact: true })).toBeFocused()
})

test('the picker fits a narrow phone and desktop, with accessible controls and touch targets', async ({ page }, info) => {
  const narrow = info.project.name.includes('mobile')
  await page.setViewportSize({ width: narrow ? 320 : 1440, height: narrow ? 650 : 1000 })
  await openNewList(page)
  const dialog = page.getByRole('dialog', { name: 'Neue Wunschliste', exact: true })
  await dialog.getByRole('button', { name: /^Symbol auswählen/ }).click()
  const picker = dialog.getByRole('region', { name: 'Symbolauswahl', exact: true })
  await picker.getByRole('combobox', { name: 'Symbolkategorie', exact: true }).selectOption('nature')
  const symbol = picker.getByRole('button', { name: 'Schmetterling 🦋', exact: true })
  await symbol.scrollIntoViewIfNeeded()
  const box = await symbol.boundingBox()
  expect(box!.width).toBeGreaterThanOrEqual(44)
  expect(box!.height).toBeGreaterThanOrEqual(44)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations.map(v => v.id)).toEqual([])
  await dialog.screenshot({ path: info.outputPath('list-symbol-picker.png') })
  await symbol.click()
  await expect(dialog.getByRole('button', { name: /^Symbol auswählen/ })).toHaveAccessibleName('Symbol auswählen, aktuell: Schmetterling 🦋')
  await expect(dialog.getByRole('button', { name: 'Liste erstellen', exact: true })).toBeDisabled()
})
