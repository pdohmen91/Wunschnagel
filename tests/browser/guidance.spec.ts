import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { openHelp, openNewList, searchWishes, openTools, compactUI } from './ui'

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Kleine & große Wünsche', exact: true })).toBeVisible()
})

test('returning users can reopen a short guide and continue from the same place', async ({ page }, info) => {
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const help = await openHelp(page)
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('listitem')).toHaveCount(3)
  await expect(dialog).toContainText('kopiere seinen Link')
  await expect(dialog).toContainText('Kaufmarkierungen der Schenkenden sind davon getrennt')
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(audit.violations).toEqual([])
  await dialog.screenshot({ path: `test-results/${info.project.name}-quick-guide.png` })
  await dialog.getByRole('button', { name: 'Verstanden' }).click()
  await expect(help).toBeFocused()
  await openHelp(page)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(help).toBeFocused()
})

test('the wish form explains missing requirements and shows the image before saving', async ({ page }, info) => {
  await page.route('**/__api/link-preview', route => route.fulfill({ json: { title: 'Titel vom Shop', image_url: 'https://shop.example/preview.svg', description: '' } }))
  await page.route('https://shop.example/preview.svg', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><rect width="64" height="64" fill="#f3a468"/></svg>' }))
  await page.getByRole('button', { name: 'Erfüllt', exact: true }).click()
  await searchWishes(page, 'alter Suchbegriff')
  await page.getByRole('button', { name: 'Wunsch hinzufügen', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const save = dialog.getByRole('button', { name: 'Wunsch speichern' })
  await expect(dialog.locator('.form-destination')).toContainText('Kleine & große Wünsche')
  await expect(save).toBeDisabled()
  await expect(save).toBeInViewport()
  await expect(save).toHaveAccessibleDescription('Füge zuerst einen gültigen Shop-Link ein.')
  await dialog.getByRole('textbox', { name: 'Dein Wunsch', exact: true }).fill('Mein eigener Titel')
  await expect(save).toBeDisabled()
  await dialog.getByRole('textbox', { name: 'Link zum Wunsch' }).fill('kein-link')
  await expect(save).toBeDisabled()
  await dialog.getByRole('textbox', { name: 'Link zum Wunsch' }).fill('https://www.thalia.de/produkt')
  await expect(save).toBeEnabled()
  await expect(dialog.getByRole('img', { name: 'Bildvorschau zum Wunsch' })).toBeVisible()
  await expect(dialog.getByRole('textbox', { name: 'Dein Wunsch', exact: true })).toHaveValue('Mein eigener Titel')
  await expect(dialog.getByRole('textbox', { name: 'Notizen & Hinweise' })).toHaveAccessibleDescription('Diese Hinweise helfen beim Schenken und werden mit der Liste geteilt. Damit das Geschenk den Nagel auf den Kopf trifft.')
  await expect(save).toBeInViewport()
  const bounds = await save.boundingBox()
  const panel = await dialog.boundingBox()
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(panel!.y + panel!.height)
  await dialog.screenshot({ path: `test-results/${info.project.name}-guided-wish.png` })
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('article').filter({ hasText: 'Mein eigener Titel' })).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(4)
  const compact = await openTools(page)
  await expect(page.getByRole('textbox', { name: 'Wünsche durchsuchen' })).toHaveValue('')
  if (compact) { await page.getByRole('button', { name: 'Abbrechen' }).click(); await expect(page.getByRole('dialog')).toHaveCount(0) }
  await expect(page.getByRole('button', { name: 'Alle Wünsche 4' })).toHaveAttribute('aria-pressed', 'true')
})

test('visibility choices explain their audience and demo sharing cannot suggest a working link', async ({ page }) => {
  await openNewList(page)
  const visibility = page.getByRole('combobox', { name: 'Wer darf deine Liste sehen?' })
  await expect(visibility).toHaveAccessibleDescription(/Nur du.*eingeladene Mitbearbeiter/)
  await visibility.selectOption('link')
  await expect(visibility).toHaveAccessibleDescription(/ohne Anmeldung.*weitergibt/)
  await expect(visibility.getByRole('option')).toHaveText(['Privat', 'Mit Link'])
  await expect(visibility.getByRole('option', { name: 'Öffentlich', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Abbrechen', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Liste teilen', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Ein kopierter Link würde deine Liste auf einem anderen Gerät noch nicht anzeigen.')
  await expect(dialog.getByRole('textbox')).toHaveCount(0)
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(audit.violations).toEqual([])
  await dialog.getByRole('button', { name: 'Zurück zur Liste' }).click()
  await expect(dialog).toHaveCount(0)
})

test('visible editing and status explanations make received wishes easy to find again', async ({ page }) => {
  await expect(page.getByRole('group', { name: 'Wünsche filtern' })).toHaveAccessibleDescription('Offen: noch gewünscht. Erfüllt: schon bekommen.')
  const card = page.getByRole('article').filter({ hasText: 'Ein guter Kaffee am Morgen' })
  await expect(card.locator('summary')).toHaveText('Bearbeiten')
  await card.locator('summary').click()
  await expect(card.getByRole('button', { name: 'Als erfüllt markieren', exact: true })).toBeVisible()
  await card.getByRole('button', { name: 'Als erfüllt markieren' }).click()
  await page.getByRole('button', { name: 'Erfüllt', exact: true }).click()
  await expect(page.locator(await compactUI(page) ? '.mobile-result-summary' : '.filter-feedback')).toContainText('1 von 3 Wünschen')
  await expect(card).toBeVisible()
  await page.getByRole('button', { name: 'Alle Wünsche zeigen', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
})
