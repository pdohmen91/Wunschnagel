import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
})

test('editing clearly indicates additional fields, then clears the cue at the end', async ({ page }, info) => {
  await page.goto('/')
  const wish = page.getByRole('article').first()
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const cue = dialog.getByText('Weitere Felder · nach unten scrollen', { exact: true })
  await expect(cue).toBeVisible()
  await expect(cue).toBeInViewport()
  await expect(dialog.locator('.form-scroll-frame')).toHaveAttribute('data-scroll-below', 'true')
  const save = dialog.getByRole('button', { name: 'Wunsch speichern', exact: true })
  await expect(save).toBeInViewport()
  expect((await cue.boundingBox())!.y + (await cue.boundingBox())!.height).toBeLessThanOrEqual((await save.boundingBox())!.y)
  await dialog.screenshot({ path: `test-results/${info.project.name}-edit-scroll-cue.png` })
  const fields = dialog.locator('.form-fields')
  await fields.evaluate(node => { node.scrollTop = node.scrollHeight })
  await expect(cue).toBeHidden()
  await expect(dialog.getByRole('button', { name: 'Shop-Vorschau neu laden' })).toBeInViewport()
  await expect(save).toBeInViewport()
  await expect(dialog.locator('.form-scroll-frame')).toHaveAttribute('data-scroll-above', 'true')
  await fields.evaluate(node => { node.scrollTop = 0 })
  await expect(cue).toBeVisible()
})

test('the cue only appears when the form no longer fits', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Suchen und sortieren', exact: true }).click()
  const cue = page.getByRole('dialog').getByText('Weitere Felder · nach unten scrollen', { exact: true })
  await expect(cue).toBeHidden()
  await page.setViewportSize({ width: 390, height: 300 })
  await expect(cue).toBeVisible()
  await expect(page.getByRole('button', { name: 'Ergebnisse anzeigen' })).toBeInViewport()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(cue).toBeHidden()
})

test('the installed iPhone header reserves a solid band above its controls', async ({ page }, info) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'standalone', { value: true, configurable: true }))
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-ios-standalone', 'true')
  await expect(page.locator('meta[name="apple-mobile-web-app-status-bar-style"]')).toHaveAttribute('content', 'black')
  expect(await page.locator('html').evaluate(node => getComputedStyle(node).backgroundColor)).toBe('rgb(53, 35, 52)')
  expect(await page.locator('.app-shell').evaluate(node => getComputedStyle(node).backgroundColor)).toBe('rgb(246, 241, 232)')
  const wordmark = await page.locator('.brand-wordmark').boundingBox()
  const controls = await page.getByRole('button', { name: 'Listen', exact: true }).boundingBox()
  expect(wordmark!.y).toBeGreaterThanOrEqual(24)
  expect(controls!.y).toBeGreaterThanOrEqual(24)
  await page.screenshot({ path: `test-results/${info.project.name}-ios-header-band.png` })
})
