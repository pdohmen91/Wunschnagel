import { expect, test } from '@playwright/test'
import { openNewList, searchWishes, chooseList, compactUI } from './ui'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Kleine & große Wünsche' })).toBeVisible()
})

test('demo renders with working images, no horizontal overflow, and honest sharing', async ({ page }, info) => {
  await expect(page.getByRole('article')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const images = page.locator('.wish-image img')
  for (const image of await images.all()) {
    await image.scrollIntoViewIfNeeded()
    await expect(image).toHaveJSProperty('complete', true)
    expect(await image.evaluate(node => (node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  }
  await page.evaluate(() => scrollTo(0, 0))
  await page.screenshot({ path: `test-results/${info.project.name}-overview.png`, fullPage: true })
  await page.getByRole('button', { name: 'Liste teilen', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('lokalen Demo')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Link kopieren' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Zurück zur Liste' }).click()
})

test('create and edit lists and wishes, search, mark fulfilled, persist, and delete', async ({ page }) => {
  await openNewList(page)
  await page.getByRole('textbox', { name: 'Name deiner Liste' }).fill('Geburtstag')
  await page.getByRole('combobox', { name: 'Wer darf deine Liste sehen?' }).selectOption('private')
  await page.getByRole('button', { name: 'Liste erstellen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Geburtstag' })).toBeVisible()
  await page.getByRole('button', { name: 'Wunsch hinzufügen', exact: true }).click()
  await page.getByRole('textbox', { name: 'Link zum Wunsch' }).fill('https://shop.de/tasse')
  await page.getByRole('textbox', { name: 'Dein Wunsch', exact: true }).fill('Lieblingstasse')
  await page.getByRole('textbox', { name: 'Notizen & Hinweise' }).fill('Bitte in Grün')
  await page.getByText('Preis & Bild-Link ergänzen', { exact: false }).click()
  await page.getByRole('textbox', { name: 'Preis in €' }).fill('24,90')
  await page.getByRole('button', { name: 'Wunsch speichern' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const card = page.getByRole('article').filter({ hasText: 'Lieblingstasse' })
  await expect(card).toContainText('24,90')
  await expect(card).toContainText('Bitte in Grün')
  await searchWishes(page, 'kein treffer')
  await expect(page.getByRole('heading', { name: 'Noch kein Treffer' })).toBeVisible()
  if (await compactUI(page)) await page.getByRole('button', { name: 'Alle Wünsche zeigen', exact: true }).click()
  else await page.getByRole('button', { name: 'Suche zurücksetzen' }).click()
  await card.locator('summary').click()
  await card.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await page.getByRole('textbox', { name: 'Dein Wunsch', exact: true }).fill('Meine grüne Tasse')
  await page.getByRole('button', { name: 'Wunsch speichern' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const updated = page.getByRole('article').filter({ hasText: 'Meine grüne Tasse' })
  await updated.locator('summary').click()
  await updated.getByRole('button', { name: 'Als erfüllt markieren' }).click()
  await expect(updated).toContainText('Erfüllt')
  await page.getByRole('button', { name: 'Erfüllt', exact: true }).click()
  await expect(updated).toBeVisible()
  await page.reload()
  await chooseList(page, 'Geburtstag')
  await expect(page.getByRole('article')).toContainText('Meine grüne Tasse')
  await page.getByRole('button', { name: 'Liste bearbeiten' }).click()
  await page.getByRole('textbox', { name: 'Name deiner Liste' }).fill('Mein Geburtstag')
  await page.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mein Geburtstag' })).toBeVisible()
  await page.getByRole('article').locator('summary').click()
  await page.getByRole('button', { name: 'Löschen', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Löschen', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: 'Liste bearbeiten' }).click()
  await page.getByRole('button', { name: 'Liste löschen', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Löschen', exact: true }).click()
  await expect(page.getByRole('button', { name: /Mein Geburtstag/ })).toHaveCount(0)
})

test('preview failure allows manual entry, and shared routes never show local data', async ({ page }) => {
  await page.getByRole('button', { name: 'Wunsch hinzufügen', exact: true }).click()
  await page.getByRole('textbox', { name: 'Link zum Wunsch' }).fill('https://shop.de/')
  await page.getByRole('button', { name: 'Erneut versuchen', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('manuell')
  await page.getByRole('button', { name: 'Abbrechen', exact: true }).click()
  await page.goto('/#/s/' + 'a'.repeat(64))
  await expect(page.getByRole('alert')).toContainText('lokalen Vorschau')
  await expect(page.getByRole('article')).toHaveCount(0)
})
