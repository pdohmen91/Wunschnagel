import { expect, test } from '@playwright/test'
import { sortWishesUI, searchWishes } from './ui'

const movingCards = () => document.getAnimations().filter(animation => {
  const target = (animation.effect as KeyframeEffect | null)?.target
  return target instanceof Element && target.matches('.wish-grid > [data-wish-id]') && animation.playState === 'running'
}).length

test('sorting and rapid filtering animate real cards without leaving blocking copies', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByRole('article').first().scrollIntoViewIfNeeded()
  await expect.poll(() => page.evaluate(movingCards)).toBe(0)
  await sortWishesUI(page, 'price-asc')
  expect(await page.evaluate(movingCards)).toBeGreaterThan(0)
  await expect(page.getByRole('article').first()).toContainText('Mehr Zeit für gute Geschichten')
  await searchWishes(page, 'Kaffee')
  await expect(page.getByRole('article')).toHaveCount(1)
  await searchWishes(page, 'nichts-passendes')
  await expect(page.getByRole('heading', { name: 'Noch kein Treffer' })).toBeVisible()
  await searchWishes(page, '')
  await expect(page.getByRole('article')).toHaveCount(3)
  await expect(page.locator('.motion-ghost')).toHaveCount(0)
  await expect.poll(() => page.evaluate(movingCards)).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const menu = page.locator('.wish-grid .card-menu').first()
  await menu.locator('summary').click()
  await menu.getByRole('button', { name: 'Als erfüllt markieren' }).click()
  await expect(page.getByRole('article').first().getByText('Erfüllt', { exact: true })).toBeVisible()
  await expect(page.locator('.completion-burst')).toHaveCount(0)
})

test('interrupted disclosure and dialog dismissal keep focus and controls usable', async ({ page }) => {
  await page.goto('/')
  const opener = page.getByRole('button', { name: 'Wunsch hinzufügen', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog')
  const details = dialog.locator('.optional-fields')
  await details.locator('summary').click()
  await expect(dialog.getByRole('textbox', { name: 'Preis in €' })).toBeVisible()
  await details.locator('summary').click()
  await expect(details).not.toHaveAttribute('open')
  await details.locator('summary').click()
  await expect(dialog.getByRole('textbox', { name: 'Bild-Link' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await opener.press('Enter')
  await expect(dialog.getByRole('textbox', { name: 'Link zum Wunsch' })).toBeFocused()
  await dialog.getByRole('button', { name: 'Abbrechen' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('reduced motion stops running movement and preserves all interactions', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('article')).toHaveCount(3)
  await sortWishesUI(page, 'price-asc')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length)).toBe(0)
  await page.getByRole('button', { name: 'Wunsch hinzufügen', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Link zum Wunsch' })).toBeFocused()
  await page.getByRole('dialog').locator('.optional-fields summary').click()
  await expect(page.getByRole('textbox', { name: 'Preis in €' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await searchWishes(page, 'Kaffee')
  await expect(page.getByRole('article')).toHaveCount(1)
  await searchWishes(page, '')
  await expect(page.getByRole('article')).toHaveCount(3)
  await expect(page.locator('.motion-ghost')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running').length)).toBe(0)
})
