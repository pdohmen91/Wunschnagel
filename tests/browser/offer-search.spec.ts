import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
})

test('cards have no automatic comparison and saving empty notes removes the placeholder', async ({ page }) => {
  const wish = page.getByRole('article').first()
  await expect(wish.getByRole('link', { name: /Preisvergleich bei idealo/ })).toHaveCount(0)
  await expect(wish.getByRole('link', { name: 'Zum Shop', exact: true })).toBeVisible()
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Angebote suchen bei' })).toHaveValue('none')
  await page.getByRole('textbox', { name: /Notizen & Hinweise/ }).fill('')
  await page.getByRole('button', { name: 'Wunsch speichern', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(wish.locator('.wish-notes, .notes-toggle, .offer-search-link')).toHaveCount(0)
  await page.reload()
  await expect(wish.locator('.wish-notes, .notes-toggle, .offer-search-link')).toHaveCount(0)
  await expect(page.getByText('Keine zusätzlichen Hinweise.', { exact: true })).toHaveCount(0)
})

test('a wish can point to used search results with an independent model name', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const wish = page.getByRole('article').first()
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await page.getByRole('combobox', { name: 'Angebote suchen bei' }).selectOption('ebay')
  await page.getByRole('textbox', { name: 'Suchbegriff', exact: false }).fill('Bialetti Moka Express 2 Tassen')
  const preview = new URL((await page.getByRole('link', { name: 'Suchergebnisse testen' }).getAttribute('href'))!)
  expect(preview.hostname).toBe('www.ebay.de')
  expect(preview.searchParams.get('_nkw')).toBe('Bialetti Moka Express 2 Tassen')
  await page.getByRole('button', { name: 'Wunsch speichern' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const search = wish.getByRole('link', { name: /Gebraucht suchen bei eBay/ })
  await search.scrollIntoViewIfNeeded()
  await expect(search).toBeVisible()
  const box = await search.boundingBox()
  expect(box!.height).toBeGreaterThanOrEqual(44)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.screenshot({ path: `test-results/${info.project.name}-used-offer-search.png` })
  await page.reload()
  await expect(search).toHaveAttribute('href', preview.href)
  await expect(wish.getByRole('heading')).toHaveText('Ein guter Kaffee am Morgen')
})

test('a saved search link preserves filters and a broken custom link cannot be saved', async ({ page }) => {
  const wish = page.getByRole('article').first()
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await page.getByRole('combobox', { name: 'Angebote suchen bei' }).selectOption('custom')
  const save = page.getByRole('button', { name: 'Wunsch speichern' })
  await expect(save).toBeDisabled()
  const input = page.getByRole('textbox', { name: 'Such- oder Preisvergleichslink', exact: true })
  await input.fill('javascript:alert(1)')
  await expect(save).toBeDisabled()
  const search = 'https://www.kleinanzeigen.de/s-suchanfrage.html?keywords=Modell+X123&maxPrice=100'
  await input.fill(search)
  await expect(save).toBeEnabled()
  await save.click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(wish.getByRole('link', { name: /Angebote finden bei/ })).toHaveAttribute('href', search)
})

test('eBay all offers saves a normal search without changing the used-only option', async ({ page }) => {
  const wish = page.getByRole('article').first()
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  const source = page.getByRole('combobox', { name: 'Angebote suchen bei' })
  await source.selectOption('ebay_all')
  await page.getByRole('textbox', { name: 'Suchbegriff', exact: false }).fill('Modell X123 & Zubehör')
  const url = new URL((await page.getByRole('link', { name: 'Suchergebnisse testen', exact: true }).getAttribute('href'))!)
  expect(url.hostname).toBe('www.ebay.de')
  expect(url.searchParams.get('_nkw')).toBe('Modell X123 & Zubehör')
  expect(url.searchParams.has('LH_ItemCondition')).toBe(false)
  await page.getByRole('button', { name: 'Wunsch speichern', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const link = wish.getByRole('link', { name: /Bei eBay suchen für/ })
  await expect(link).toHaveAttribute('href', url.href)
  await expect(link).toHaveAttribute('rel', 'noopener noreferrer')
  await page.reload()
  await expect(link).toHaveAttribute('href', url.href)
  await wish.locator('summary').click()
  await wish.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await expect(source).toHaveValue('ebay_all')
  await source.selectOption('ebay')
  const usedUrl = new URL((await page.getByRole('link', { name: 'Suchergebnisse testen', exact: true }).getAttribute('href'))!)
  expect(usedUrl.searchParams.has('LH_ItemCondition')).toBe(true)
})
